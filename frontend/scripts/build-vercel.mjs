import { writeFileSync, unlinkSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

// Only the public backend origin goes into the browser bundle. Never include API_KEY here.
const value = process.env.API_ORIGIN;
if (!value) throw new Error('Set API_ORIGIN to your Next.js backend URL in this Vercel project.');
const url = new URL(value);
if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash || !['', '/'].includes(url.pathname)) {
  throw new Error('API_ORIGIN must be an HTTPS origin without credentials, a path, query or fragment.');
}
const generated = new URL('../src/app/api.config.vercel.ts', import.meta.url);
try {
  writeFileSync(generated, `// Generated by build-vercel.mjs.\nexport const API_BASE_URL = ${JSON.stringify(url.origin)};\n`);
  const result = spawnSync(process.execPath, ['node_modules/@angular/cli/bin/ng.js', 'build', '--configuration', 'vercel'], { stdio: 'inherit' });
  if (result.error) throw result.error;
  process.exitCode = result.status ?? 1;
} finally {
  try { unlinkSync(generated); } catch (error) { if (error.code !== 'ENOENT') throw error; }
}
