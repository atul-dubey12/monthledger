-- Things that happen every month (salary, home money, SIP, recharge, gym fee).
-- Nothing is posted automatically: the app lists what's due and the person taps Paid.
create table recurring (
  id            bigint generated by default as identity primary key,
  name          varchar(40)   not null,
  kind          varchar(20)   not null,
  amount        numeric(12,2) not null,
  category_id   bigint        not null references categories(id),
  goal_id       bigint        references goals(id),
  day_of_month  integer       not null,
  payment_mode  varchar(10),
  active        boolean       not null default true,
  constraint recurring_day check (day_of_month between 1 and 31)
);

-- The recurring item an entry paid, so "paid this month" is exact.
alter table entries add column recurring_id bigint references recurring(id);
