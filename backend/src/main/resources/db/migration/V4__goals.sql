create table goals (
  id               bigint generated by default as identity primary key,
  name             varchar(40)   not null,
  icon             varchar(8)    not null,
  target_amount    numeric(12,2) not null,
  -- Money already saved before tracking started, so progress starts from the truth.
  starting_amount  numeric(12,2) not null default 0,
  target_date      date,
  archived         boolean       not null default false
);

-- A saving (or withdrawal) can count towards one goal.
alter table entries add column goal_id bigint references goals(id);
